"""Render the latest result of every experiment as one Markdown file.

The research report quotes its numbers from this file, and this file is generated only from the
versioned result directories, so every number in the report can be traced to a run, a config and
a commit.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

EXPERIMENTS = ("e1_runs", "e2_verifier", "e3_critic", "e4_fluency", "e5_reproducibility")


def _cell(v: Any) -> str:
    if v is None:
        return "n/a"
    if isinstance(v, float):
        return f"{v:.3f}"
    if isinstance(v, list):
        return ", ".join(map(str, v)) or "none"
    return str(v).replace("|", "\\|")


def _table(t: dict[str, Any]) -> list[str]:
    cols = t["columns"]
    out = [f"**{t['caption']}**", "", "| " + " | ".join(c["label"] for c in cols) + " |",
           "|" + "|".join("---:" if c["align"] == "r" else "---" for c in cols) + "|"]  # fmt: skip
    out += ["| " + " | ".join(_cell(r.get(c["key"])) for c in cols) + " |" for r in t["rows"]]
    return [*out, ""]


def render(results: Path) -> str:
    lines = [
        "# Results",
        "",
        "Generated by `discoverylab results` from `results/<experiment>/LATEST`. Do not edit by hand.",
        "",
    ]
    for name in EXPERIMENTS:
        latest = results / name / "LATEST"
        if not latest.is_file():
            lines += [f"## {name}", "", "Status: pending (no result directory).", ""]
            continue
        run_id = latest.read_text(encoding="utf-8").strip()
        d = results / name / run_id
        s = json.loads((d / "summary.json").read_text(encoding="utf-8"))
        p = json.loads((d / "provenance.json").read_text(encoding="utf-8"))
        lines += [f"## {s['title']}", "", f"*{s['question']}*", "",
                  f"Result `results/{name}/{run_id}` · commit `{p['commit'][:7]}`{' (dirty)' if p['dirty'] else ''}"
                  f" · {p['created_at']} · {p['runtime_seconds']} s", ""]  # fmt: skip
        lines += [f"- {f}" for f in s["findings"]] + [""]
        for t in s["tables"]:
            lines += _table(t)
        if s["notes"]:
            lines += ["Notes:", ""] + [f"- {n}" for n in s["notes"]] + [""]
    return "\n".join(lines).rstrip() + "\n"


def write(results: Path, out: Path) -> Path:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(results), encoding="utf-8")
    return out
